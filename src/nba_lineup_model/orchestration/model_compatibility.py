"""Portable, reviewed compatibility of an accepted model's calculation code.

The checked-in policy is NOT regenerated by deployment. It records the reviewed
source fingerprints for an accepted model revision. A later change to any
transitive internal dependency fails until reviewed; unrelated reports do not.
The enclosing sealed package protects this policy just like executable code.
"""
from __future__ import annotations

import ast
import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT_MODULES = (
    "nba_lineup_model.season.daily_model_replay",
    "nba_lineup_model.web_api.inference",
)


def calculation_inventory(code_root: Path) -> dict[str, str]:
    root = Path(code_root).resolve()
    pending = list(ROOT_MODULES)
    visited = set()
    inventory = {}
    while pending:
        module = pending.pop()
        if module in visited:
            continue
        visited.add(module)
        stem = root / "src" / Path(*module.split("."))
        path = stem.with_suffix(".py")
        if not path.is_file():
            path = stem / "__init__.py"
        if not path.is_file():
            if module in ROOT_MODULES:
                raise ValueError(f"Missing model calculation root: {module}")
            # A name imported from a module may be a function, not a submodule.
            continue
        if path.is_symlink() or not path.resolve().is_relative_to(root):
            raise ValueError(f"Calculation source escapes its code package: {module}")
        source = path.read_bytes()
        inventory[path.relative_to(root).as_posix()] = hashlib.sha256(source).hexdigest()
        parts = module.split(".")
        pending.extend(".".join(parts[:n]) for n in range(1, len(parts)))
        for node in ast.walk(ast.parse(source)):
            imports = []
            if isinstance(node, ast.Import):
                imports = [alias.name for alias in node.names]
            elif isinstance(node, ast.ImportFrom):
                package = module if path.name == "__init__.py" else module.rsplit(".", 1)[0]
                base = (importlib.util.resolve_name("." * node.level + (node.module or ""), package)
                        if node.level else node.module or "")
                imports = [base, *[base + "." + alias.name for alias in node.names]]
            pending.extend(name for name in imports
                           if name == "nba_lineup_model" or name.startswith("nba_lineup_model."))
    for relative in ("pyproject.toml", "uv.lock", "deploy/orchestration-requirements.txt",
                     "deploy/web-requirements.txt"):
        path = root / relative
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"Missing or invalid dependency definition: {relative}")
        inventory[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    return dict(sorted(inventory.items()))


def require_compatible_calculations(code_root: Path, accepted_revision: str) -> dict:
    if not re.fullmatch(r"[0-9a-f]{40}", accepted_revision):
        raise ValueError("Accepted model revision must be an exact Git commit")
    policy_path = (Path(code_root) / "src/nba_lineup_model/orchestration/model_compatibility"
                   / (accepted_revision + ".json"))
    if not policy_path.is_file() or policy_path.is_symlink():
        raise ValueError("No reviewed calculation compatibility policy for accepted model")
    policy = json.loads(policy_path.read_text())
    if policy.get("schema_version") != 1 or policy.get("accepted_revision") != accepted_revision:
        raise ValueError("Model compatibility policy identifies different accepted code")
    expected = policy.get("compatible_files")
    if not isinstance(expected, dict) or not expected:
        raise ValueError("Model compatibility policy has no calculation inventory")
    actual = calculation_inventory(code_root)
    changed = sorted(path for path in set(actual) | set(expected)
                     if actual.get(path) != expected.get(path))
    if changed:
        raise ValueError("Model implementation changed outside its reviewed compatibility policy; "
                         "an explicitly approved causal replay or equivalence review is required: "
                         + ", ".join(changed))
    return {"accepted_revision": accepted_revision, "verified_file_count": len(actual),
            "policy_sha256": hashlib.sha256(policy_path.read_bytes()).hexdigest()}
